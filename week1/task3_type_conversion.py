int_test = 22
int_to_float = float(int_test)
print(" Int to Float:", int_to_float)

float_test = 15.55
float_to_int = int(float_test)
print(" Float to Int:", float_to_int)

int_to_str = str(int_test)
print(" Int to String:", int_to_str)

str_test = "25"
str_to_int = int(str_test)
print(" String to Int:", str_to_int)

int_to_bool = bool(int_test)
print(" Int to Bool:", int_to_bool)